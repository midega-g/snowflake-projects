-- Section 10: dynamic data masking on CLICKS (lab "Security showcase", part 2).
-- Run before 19_dynamic_table.sql. Attaching a policy to a table that a dynamic table already reads makes Snowflake rebuild it in full (about 0.9 AI credits).
USE ROLE SNOWFLAKE_INTELLIGENCE_ADMIN;
USE WAREHOUSE DASH_WH_SI;
USE SCHEMA DASH_DB_SI.RETAIL;

CREATE OR REPLACE MASKING POLICY MASK_ENGAGEMENT_CLICKS AS (val NUMBER)
RETURNS NUMBER ->
  CASE
    WHEN CURRENT_ROLE() IN ('SNOWFLAKE_INTELLIGENCE_ADMIN', 'ACCOUNTADMIN') THEN val
    ELSE 0 -- masked value for other roles
  END
  COMMENT = 'Shows CLICKS to SNOWFLAKE_INTELLIGENCE_ADMIN and ACCOUNTADMIN, and 0 to every other role.';

ALTER TABLE MARKETING_CAMPAIGN_METRICS MODIFY COLUMN CLICKS SET MASKING POLICY MASK_ENGAGEMENT_CLICKS;

SELECT * FROM TABLE(DASH_DB_SI.INFORMATION_SCHEMA.POLICY_REFERENCES(
    POLICY_NAME => 'MASK_ENGAGEMENT_CLICKS'
));
